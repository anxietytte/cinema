-- ПРОВЕРОЧНЫЕ ЗАПРОСЫ

SELECT '=== Статусы ===' AS '';
SELECT * FROM statuses;

SELECT '=== Жанры ===' AS '';
SELECT * FROM genres;

SELECT '=== Пользователи ===' AS '';
SELECT id, email, name, phone, registered_at, is_active FROM users;

SELECT '=== Фильмы ===' AS '';
SELECT id, title, year, country, rating FROM movie;

SELECT '=== Связь фильмов с жанрами ===' AS '';
SELECT m.title as Фильм, g.name as Жанр
FROM movie_genres mg
JOIN movie m ON mg.movie_id = m.id
JOIN genres g ON mg.genre_id = g.id
ORDER BY m.title;

SELECT '=== Бронирования ===' AS '';
SELECT 
    b.id as 'ID брони',
    u.name as 'Пользователь',
    m.title as 'Фильм',
    s.name as 'Статус',
    b.seats as 'Места',
    b.session_date as 'Дата сеанса',
    b.total_price as 'Сумма'
FROM bookings b
JOIN users u ON b.user_id = u.id
JOIN movie m ON b.movie_id = m.id
JOIN statuses s ON b.status_id = s.id
ORDER BY b.session_date;
